#!/bin/sh
# Write probed.lisp: table entries (DEFS) for the functions libguile
# exports that are Scheme procedures but that Guile's manual doesn't pair
# with one (so extract-manual.lisp can't find them), probed from an
# installed GNU Guile 3.0.11:
#
#   sh probe-procedures.sh $(pkg-config --cflags guile-3.0) > probed.lisp
#
# Its arguments are the C compiler's flags for Guile's headers.
# For each function libguile exports (exports-3.0.11.txt) that
# table.lisp and scheme.lisp don't have:
# 1. its C type, as the C compiler reports it for an initialization
#    with a mismatched type: only functions all of whose arguments and
#    whose result are SCM are kept;
# 2. the Scheme procedure of its name in Guile's root module (or the
#    modules impl.lisp's GUILE-PROCEDURE looks in), by
#    libguile's naming (scm_char_less_p is char<?, scm_cons_star cons*,
#    scm_sys_foo %foo, _x is !, _to_ is ->), and that procedure's arity
#    from the guile on PATH.
# An entry is written when the C function's argument count is the
# procedure's (required, optional, a list for the rest), or one the
# procedure accepts: scm_logxor (a b) calls (logxor a b).
set -e
here=$(cd "$(dirname "$0")" && pwd)
[ $# -gt 0 ] || { echo 'usage: probe-procedures.sh $(pkg-config --cflags guile-3.0)' >&2; exit 2; }
tmp=${TMPDIR:-/tmp}/probe-procedures.$$
mkdir -p "$tmp"
trap 'rm -rf "$tmp"' EXIT
grep -ho '"scm_[A-Za-z0-9_]*"' "$here/table.lisp" "$here/scheme.lisp" | tr -d '"' | sort -u > "$tmp/have"
sort -u "$here/exports-3.0.11.txt" | comm -23 - "$tmp/have" > "$tmp/names"

# 1. C types
{
  printf '#include <libguile.h>\nstruct probe_t { int x; };\n'
  while read -r f; do printf 'struct probe_t probe_%s = %s;\n' "$f" "$f"; done < "$tmp/names"
} > "$tmp/types.c"
${CC:-cc} "$@" -fsyntax-only -ferror-limit=0 "$tmp/types.c" 2> "$tmp/types.err" || true
# line N of types.c is the (N-2)th name; keep those of SCM (SCM, ...) or SCM (void)
sed -n "s/^.*types\.c:\([0-9]*\):[0-9]*: error: .*incompatible type 'SCM (\([^']*\))'.*$/\1 \2/p" "$tmp/types.err" \
  | awk 'NR == FNR { name[NR + 2] = $0; next }
         { line = $1; $1 = ""; args = substr($0, 2)
           if (args == "void") n = 0
           else { n = split(args, a, ", "); for (i = 1; i <= n; i++) if (a[i] != "SCM") n = -1 }
           if (n >= 0) print name[line], n }' "$tmp/names" - > "$tmp/scm-only"

# 2. the procedures and their arities
cat > "$tmp/arity.scm" <<'EOF'
(use-modules (ice-9 rdelim) (ice-9 regex))
;; the modules a name is looked for in, as impl.lisp's GUILE-PROCEDURE does
(define modules
  (cons the-root-module
        (map resolve-interface '((ice-9 ports) (oop goops) (ice-9 textual-ports) (ice-9 binary-ports)
                                 (ice-9 weak-vector) (ice-9 threads) (system foreign) (srfi srfi-4 gnu)
                                 (ice-9 i18n) (ice-9 local-eval) (system vm program)))))
(define (lookup sym)
  (let loop ((ms modules))
    (and (pair? ms)
         (let ((v (and (module-defined? (car ms) sym) (module-ref (car ms) sym))))
           (if (procedure? v) v (loop (cdr ms)))))))
(define (subst s from to) (regexp-substitute/global #f from s 'pre to 'post))
(define (variants s)
  (let* ((s (subst s "_to_" "->"))
         (s (subst s "_star$" "*"))
         (s (subst s "_star_x$" "*!"))
         (s (subst s "(^|_)eq_p$" "=?"))
         (s (subst s "(^|_)less_p$" "<?"))
         (s (subst s "(^|_)gr_p$" ">?"))
         (s (subst s "(^|_)leq_p$" "<=?"))
         (s (subst s "(^|_)geq_p$" ">=?"))
         (s (subst s "_p$" "?"))
         (s (subst s "_x$" "!"))
         (d (string-map (lambda (c) (if (char=? c #\_) #\- c)) s)))
    (list d (subst (subst d "^num-=\\?$" "=") "^(<|>|<=|>=)\\?$" "\\1"))))
(define (procedure-for c)
  (let* ((s (substring c 4))
         (sys (string-prefix? "sys_" s))
         (s (if sys (substring s 4) s)))
    (let loop ((names (append (if sys (map (lambda (x) (string-append "%" x)) (variants s)) '())
                              (variants s))))
      (and (pair? names)
           (let ((v (lookup (string->symbol (car names)))))
             (if v
                 (cons (car names) (procedure-minimum-arity v))
                 (loop (cdr names))))))))
(let loop ()
  (let ((line (read-line)))
    (unless (eof-object? line)
      (let* ((fields (string-split line #\space))
             (c (car fields))
             (n (string->number (cadr fields)))
             (p (procedure-for c)))
        (when p
          (let ((name (car p)) (req (cadr p)) (opt (caddr p)) (rest (cadddr p)))
            (cond ((= n (+ req opt (if rest 1 0)))
                   (format #t "(defs ~s ~s ~a ~a ~a)~%" c name req opt (if rest "t" "nil")))
                  ((and (<= req n) (or rest (<= n (+ req opt))))
                   (format #t "(defs ~s ~s ~a 0 nil)~%" c name n))))))
      (loop))))
EOF
{
  printf ';;;; Generated by src/libguile/probe-procedures.sh from GNU Guile 3.0.11:\n'
  printf ";;;; don't edit.  libguile's C functions that are Scheme procedures the\n"
  printf ';;;; manual does not pair with one (table.lisp, DEFS): the C name, the\n'
  printf ';;;; procedure, its required and optional arguments, and whether it has a\n'
  printf ';;;; rest list.\n\n(in-package "QUASISCHEME-LIBGUILE")\n\n'
  guile --no-auto-compile "$tmp/arity.scm" < "$tmp/scm-only" | sort
}
